"""Write ATTRIBUTION.md from manifest.json and print per-category counts/sizes."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
assets = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))["assets"]

lines = ["# Attribution", "", "Generated by `tools/gen_attribution.py` from `manifest.json`. Do not edit by hand.", "",
         "## CC BY assets (attribution required)", "", "| File | Author | License | Source |", "|---|---|---|---|"]
for e in assets:
    if e["attribution_required"]:
        lines.append(f"| `{e['file']}` | {e['author'].replace('|', '/')} | [{e['license']}]({e['license_url']}) | [source]({e['source_page']}) |")
lines += ["", "## CC0 / public domain assets (credit given as courtesy)", "", "| File | Author | License | Source |", "|---|---|---|---|"]
for e in assets:
    if not e["attribution_required"]:
        lines.append(f"| `{e['file']}` | {e['author'].replace('|', '/')} | {e['license']} | [source]({e['source_page']}) |")
(ROOT / "ATTRIBUTION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

stats = defaultdict(lambda: [0, 0])
lic = defaultdict(int)
for e in assets:
    stats[e["category"]][0] += 1
    stats[e["category"]][1] += e["size"]
    lic[e["license_code"]] += 1
for c, (n, s) in sorted(stats.items()):
    print(f"| {c} | {n} | {s / 1e6:.1f} MB |")
print("total", len(assets), f"{sum(e['size'] for e in assets) / 1e6:.1f} MB", dict(lic))
